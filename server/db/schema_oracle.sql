-- ====================================================================
-- Vehicle Rental & Fleet Management System - Oracle Database DDL
-- Compatible with Oracle Database (12c, 18c, 19c, 21c, 23c & Oracle SQL Developer)
-- Foreign Keys, Identity Columns, Check Constraints & Performance Indexes
-- ====================================================================

-- 1. Users Table
CREATE TABLE users (
    user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR2(100) NOT NULL,
    phone         VARCHAR2(25),
    email         VARCHAR2(150) UNIQUE NOT NULL,
    password_hash VARCHAR2(255),
    role          VARCHAR2(20) DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
    is_verified   NUMBER(1) DEFAULT 0 CHECK (is_verified IN (0, 1)),
    is_blocked    NUMBER(1) DEFAULT 0 CHECK (is_blocked IN (0, 1)),
    google_id     VARCHAR2(255),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Email OTPs Table
CREATE TABLE email_otps (
    otp_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR2(150) NOT NULL,
    otp_hash   VARCHAR2(255) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used       NUMBER(1) DEFAULT 0 CHECK (used IN (0, 1))
);

-- 3. Vehicles Table
CREATE TABLE vehicles (
    vehicle_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR2(100) NOT NULL,
    brand               VARCHAR2(100) NOT NULL,
    category            VARCHAR2(20) NOT NULL CHECK (category IN ('Hatchback', 'Sedan', 'SUV', 'MUV', 'Luxury')),
    fuel_type           VARCHAR2(50) NOT NULL,
    transmission        VARCHAR2(50) NOT NULL,
    seats               NUMBER(2) NOT NULL,
    price_per_day       NUMBER(10, 2) NOT NULL,
    price_per_hour      NUMBER(10, 2) NOT NULL,
    price_per_km        NUMBER(10, 2) NOT NULL,
    security_deposit    NUMBER(10, 2) NOT NULL,
    status              VARCHAR2(20) DEFAULT 'Available' CHECK (status IN ('Available', 'Rented', 'In Service')),
    image_url           VARCHAR2(500),
    is_chauffeur_driven NUMBER(1) DEFAULT 0 CHECK (is_chauffeur_driven IN (0, 1)),
    insurance_expiry    DATE,
    permit_expiry       DATE,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. Bookings Table
CREATE TABLE bookings (
    booking_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         NUMBER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    vehicle_id      NUMBER NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE CASCADE,
    start_datetime  TIMESTAMP NOT NULL,
    end_datetime    TIMESTAMP NOT NULL,
    pricing_type    VARCHAR2(10) DEFAULT 'day' CHECK (pricing_type IN ('day', 'hour', 'km')),
    total_amount    NUMBER(10, 2) NOT NULL,
    deposit_amount  NUMBER(10, 2) DEFAULT 0,
    discount_amount NUMBER(10, 2) DEFAULT 0,
    late_fee        NUMBER(10, 2) DEFAULT 0,
    status          VARCHAR2(20) DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Active', 'Completed', 'Cancelled')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. Payments Table
CREATE TABLE payments (
    payment_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id          NUMBER NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
    amount              NUMBER(10, 2) NOT NULL,
    method              VARCHAR2(50) DEFAULT 'Razorpay',
    razorpay_order_id   VARCHAR2(100),
    razorpay_payment_id VARCHAR2(100),
    payment_status      VARCHAR2(20) DEFAULT 'Pending' CHECK (payment_status IN ('Pending', 'Paid', 'Failed', 'Refunded')),
    paid_at             TIMESTAMP
);

-- 6. Maintenance Records Table
CREATE TABLE maintenance (
    maintenance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id     NUMBER NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE CASCADE,
    service_date   DATE NOT NULL,
    cost           NUMBER(10, 2) NOT NULL,
    next_due_date  DATE,
    notes          VARCHAR2(1000)
);

-- 7. Fuel Records Table
CREATE TABLE fuel_records (
    fuel_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id NUMBER NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE CASCADE,
    date       DATE NOT NULL,
    litres     NUMBER(10, 2) NOT NULL,
    cost       NUMBER(10, 2) NOT NULL
);

-- 8. Drivers Table
CREATE TABLE drivers (
    driver_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR2(100) NOT NULL,
    phone      VARCHAR2(25) NOT NULL,
    license_no VARCHAR2(50) NOT NULL,
    vehicle_id NUMBER REFERENCES vehicles(vehicle_id) ON DELETE SET NULL
);

-- 9. Reviews Table
CREATE TABLE reviews (
    review_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    NUMBER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    vehicle_id NUMBER NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE CASCADE,
    booking_id NUMBER REFERENCES bookings(booking_id) ON DELETE SET NULL,
    rating     NUMBER(1) NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment    VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 10. Discounts Table
CREATE TABLE discounts (
    discount_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR2(50) UNIQUE NOT NULL,
    percent     NUMBER(5, 2) NOT NULL,
    valid_from  DATE,
    valid_to    DATE,
    active      NUMBER(1) DEFAULT 1 CHECK (active IN (0, 1))
);

-- 11. Vehicle Documents Table
CREATE TABLE vehicle_documents (
    doc_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id  NUMBER NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE CASCADE,
    doc_type    VARCHAR2(100) NOT NULL,
    file_url    VARCHAR2(500),
    expiry_date DATE
);

-- ====================================================================
-- Performance Indexes for Oracle Database
-- ====================================================================
CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_vehicles_category ON vehicles(category);
CREATE INDEX idx_vehicles_status ON vehicles(status);
CREATE INDEX idx_bookings_vehicle_dates ON bookings(vehicle_id, start_datetime, end_datetime);
CREATE INDEX idx_bookings_user ON bookings(user_id);
CREATE INDEX idx_bookings_status ON bookings(status);
CREATE INDEX idx_payments_booking ON payments(booking_id);
CREATE INDEX idx_maintenance_vehicle ON maintenance(vehicle_id);
CREATE INDEX idx_fuel_vehicle ON fuel_records(vehicle_id);
CREATE INDEX idx_reviews_vehicle ON reviews(vehicle_id);
CREATE INDEX idx_documents_vehicle ON vehicle_documents(vehicle_id);
